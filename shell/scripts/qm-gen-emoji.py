def from_system(path):
    """Parse emoji-test.txt into (emoji, name, keywords, group) tuples."""
    out = []
    group = ""
    subgroup = ""
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith("# group:"):
                group = line.split(":", 1)[1].strip().lower()
                group = re.sub(r"[^a-z]+", "-", group).strip("-")
                continue
            if line.startswith("# subgroup:"):
                subgroup = line.split(":", 1)[1].strip().replace("-", " ")
                continue
            if not line or line.startswith("#"):
                continue
            m = re.match(r"^([0-9A-F ]+?)\s*;\s*(\S+)\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$", line)
            if not m:
                continue
            if m.group(2) != "fully-qualified":
                continue
            emoji = m.group(3)
            name = m.group(4).strip()
            # Skip skin-tone / hair variants to keep the grid sane.
            if "skin tone" in name or ": " in name and any(w in name for w in ("hair",)):
                continue
            keywords = " ".join(sorted(set(re.findall(r"[a-z]+", (subgroup + " " + name).lower()))))
            out.append((emoji, name, keywords, group))
    return out


def main():
    entries = []
    if os.path.isfile(SYSTEM_FILE):
        try:
            entries = from_system(SYSTEM_FILE)
        except Exception as exc:  # noqa: BLE001
            print(f"qm-gen-emoji: failed to parse {SYSTEM_FILE}: {exc}", file=sys.stderr)
    source = "system"
    if not entries:
        entries = CURATED
        source = "curated"

    seen = set()
    rows = []
    for emoji, name, keywords, group in entries:
        if emoji in seen:
            continue
        seen.add(emoji)
        rows.append({"e": emoji, "n": name, "k": keywords, "g": group})

    os.makedirs(ASSETS, exist_ok=True)
    with open(os.path.join(ASSETS, "emoji.json"), "w", encoding="utf-8") as fh:
        json.dump(rows, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write("\n")
    with open(os.path.join(ASSETS, "emoji.txt"), "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(f"{r['e']} {r['n']}\n")
    print(f"qm-gen-emoji: wrote {len(rows)} emoji ({source}) to {ASSETS}")


if __name__ == "__main__":
    main()
