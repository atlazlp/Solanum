#!/usr/bin/env bash
# Keep the Caelestia/Quickshell bar on the preferred main monitor (default DP-2).
# When that output disappears, promote the rightmost remaining monitor: move the bar
# there, write a compacted layout into hypr-monitors-runtime.conf, and focus it.
# When preferred returns, restore the default layout file and bar exclusions.
set -eu

PREFERRED_MAIN="${PREFERRED_MAIN:-DP-2}"
SHELL_JSON="${HOME}/.config/caelestia/shell.json"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/caelestia"
STATE_FILE="${STATE_DIR}/main-monitor-hotplug"
MONITORS_RUNTIME="${HOME}/.config/caelestia/hypr-monitors-runtime.conf"
MONITORS_DEFAULT="${HOME}/.config/caelestia/hypr-monitors-default.conf"
DEBOUNCE_SEC="${MAIN_MONITOR_DEBOUNCE:-0.8}"
QM_ROOT_FILE="${HOME}/.config/caelestia/quantum-moon-root"

log() {
	printf '%s\n' "main-monitor-hotplug: $*" >&2
}

toast() {
	local kind="$1" msg="$2"
	if command -v caelestia >/dev/null 2>&1; then
		caelestia shell toaster "${kind}" "Monitors" "${msg}" "" 2>/dev/null || true
	fi
}

wait_for_hypr() {
	local i
	for i in $(seq 1 60); do
		if [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]] &&
			[[ -S "${XDG_RUNTIME_DIR}/hypr/${HYPRLAND_INSTANCE_SIGNATURE}/.socket2.sock" ]] &&
			hyprctl monitors -j >/dev/null 2>&1; then
			return 0
		fi
		if [[ -z "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]] && [[ -d "${XDG_RUNTIME_DIR}/hypr" ]]; then
			HYPRLAND_INSTANCE_SIGNATURE="$(find "${XDG_RUNTIME_DIR}/hypr" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2>/dev/null | head -n1 || true)"
			export HYPRLAND_INSTANCE_SIGNATURE
		fi
		sleep 0.5
	done
	return 1
}

monitors_json() {
	hyprctl monitors -j 2>/dev/null | jq -c '[.[] | select(.disabled != true)]' || echo '[]'
}

preferred_connected() {
	monitors_json | jq -e --arg n "${PREFERRED_MAIN}" 'any(.[]; .name == $n)' >/dev/null 2>&1
}

pick_bar_host() {
	local json
	json="$(monitors_json)"
	if echo "${json}" | jq -e --arg n "${PREFERRED_MAIN}" 'any(.[]; .name == $n)' >/dev/null 2>&1; then
		printf '%s' "${PREFERRED_MAIN}"
		return
	fi
	echo "${json}" | jq -r 'if length == 0 then empty else (sort_by(.x, .y) | last | .name) end'
}

logical_width() {
	local w h scale transform
	w="$1"
	h="$2"
	scale="$3"
	transform="$4"
	awk -v w="${w}" -v h="${h}" -v s="${scale}" -v t="${transform}" 'BEGIN {
		if (s <= 0) s = 1
		if (t == 1 || t == 3) print int(h / s + 0.5)
		else print int(w / s + 0.5)
	}'
}

format_refresh() {
	awk -v r="$1" 'BEGIN {
		if (r == int(r)) printf "%d", r
		else printf "%.2f", r
	}'
}

format_scale() {
	awk -v s="$1" 'BEGIN {
		if (s == int(s)) printf "%d", s
		else printf "%s", s
	}'
}

layout_is_adjacent() {
	local json
	json="$(monitors_json)"
	echo "${json}" | jq -e '
		def lw:
			if (.transform == 1 or .transform == 3)
			then (.height / (if .scale <= 0 then 1 else .scale end) | round)
			else (.width / (if .scale <= 0 then 1 else .scale end) | round)
			end;
		(sort_by(.x, .y)) as $m
		| if ($m | length) <= 1 then true
		  else
		    reduce range(1; $m | length) as $i (true;
		      . and (($m[$i].x - ($m[$i-1].x + ($m[$i-1] | lw))) | fabs) <= 2
		    )
		  end
	' >/dev/null 2>&1
}

write_default_monitors_conf() {
	if [[ -f "${MONITORS_DEFAULT}" ]]; then
		install -m644 "${MONITORS_DEFAULT}" "${MONITORS_RUNTIME}"
	else
		log "missing ${MONITORS_DEFAULT}"
		return 1
	fi
}

# Pack currently connected monitors left→right into the runtime conf (source of truth).
write_compacted_monitors_conf() {
	local json sorted count i name w h scale transform refresh mode x lw line
	json="$(monitors_json)"
	count="$(echo "${json}" | jq 'length')"
	[[ "${count}" -gt 0 ]] || return 0

	sorted="$(echo "${json}" | jq -c 'sort_by(.x, .y)')"
	{
		echo "# Generated by main-monitor-hotplug (fallback — preferred ${PREFERRED_MAIN} missing)"
		echo "# $(date -Iseconds)"
		x=0
		i=0
		while [[ "${i}" -lt "${count}" ]]; do
			name="$(echo "${sorted}" | jq -r ".[${i}].name")"
			w="$(echo "${sorted}" | jq -r ".[${i}].width")"
			h="$(echo "${sorted}" | jq -r ".[${i}].height")"
			scale="$(format_scale "$(echo "${sorted}" | jq -r ".[${i}].scale")")"
			transform="$(echo "${sorted}" | jq -r ".[${i}].transform")"
			refresh="$(format_refresh "$(echo "${sorted}" | jq -r ".[${i}].refreshRate")")"
			mode="${w}x${h}@${refresh}"
			if [[ "${transform}" != "0" ]]; then
				line="monitor=${name},${mode},${x}x0,${scale},transform,${transform}"
			else
				line="monitor=${name},${mode},${x}x0,${scale}"
			fi
			echo "${line}"
			log "runtime place ${name} at ${x}x0"
			lw="$(logical_width "${w}" "${h}" "${scale}" "${transform}")"
			x=$((x + lw))
			i=$((i + 1))
		done
	} >"${MONITORS_RUNTIME}.tmp"
	mv "${MONITORS_RUNTIME}.tmp" "${MONITORS_RUNTIME}"
}

reload_monitors() {
	hyprctl reload >/dev/null 2>&1 || true
	sleep 0.35
}

write_state() {
	local host="$1" announced="${2:-0}"
	mkdir -p "${STATE_DIR}"
	printf 'compacted=1\nbar_host=%s\nannounced=%s\n' "${host}" "${announced}" >"${STATE_FILE}"
}

state_announced() {
	[[ -f "${STATE_FILE}" ]] || return 1
	awk -F= '/^announced=/ { exit !($2 == 1) }' "${STATE_FILE}"
}

current_fallback_host() {
	[[ -f "${STATE_FILE}" ]] || return 1
	awk -F= '/^bar_host=/ { print $2; exit }' "${STATE_FILE}"
}

set_bar_host() {
	local host="$1"
	local json excluded tmp current
	[[ -n "${host}" ]] || return 1
	[[ -f "${SHELL_JSON}" ]] || {
		log "missing ${SHELL_JSON}"
		return 1
	}
	command -v jq >/dev/null 2>&1 || {
		log "jq required"
		return 1
	}

	json="$(monitors_json)"
	excluded="$(echo "${json}" | jq -c --arg h "${host}" '[.[].name | select(. != $h)]')"
	current="$(jq -c '.bar.excludedScreens // []' "${SHELL_JSON}")"
	# -n: do not read stdin (event-loop safe)
	if jq -ne --argjson a "${current}" --argjson b "${excluded}" '($a | sort) == ($b | sort)' >/dev/null 2>&1; then
		return 1
	fi

	tmp="$(mktemp "${SHELL_JSON}.tmp.XXXXXX")"
	jq --argjson ex "${excluded}" '.bar.excludedScreens = $ex' "${SHELL_JSON}" >"${tmp}"
	install -m644 "${tmp}" "${SHELL_JSON}"
	rm -f "${tmp}"
	log "bar host=${host} excludedScreens=${excluded}"
	return 0
}

focus_main() {
	local host="$1"
	[[ -n "${host}" ]] || return 0
	hyprctl dispatch focusmonitor "${host}" >/dev/null 2>&1 || true
}

reapply_wallpapers() {
	local qm
	[[ -f "${QM_ROOT_FILE}" ]] || return 0
	read -r qm <"${QM_ROOT_FILE}" || return 0
	[[ -n "${qm}" && -x "${qm}/scripts/qm-apply" ]] || return 0
	"${qm}/scripts/qm-apply" --persisted >/dev/null 2>&1 || true
}

apply() {
	local host was_compacted=0 already_announced=0
	sleep 0.2
	if [[ -f "${STATE_FILE}" ]]; then
		was_compacted=1
		if state_announced; then
			already_announced=1
		fi
	fi

	if preferred_connected; then
		host="${PREFERRED_MAIN}"
		if [[ "${was_compacted}" -eq 1 ]]; then
			log "preferred ${PREFERRED_MAIN} back — restoring default monitor layout"
			write_default_monitors_conf
			reload_monitors
			rm -f "${STATE_FILE}"
			set_bar_host "${host}" || true
			focus_main "${host}"
			reapply_wallpapers
			toast info "Main monitor restored (${PREFERRED_MAIN})"
			log "restored preferred=${PREFERRED_MAIN}"
			return 0
		fi
		set_bar_host "${host}" || true
		return 0
	fi

	host="$(pick_bar_host)"
	[[ -n "${host}" ]] || {
		log "no monitors connected"
		return 0
	}

	if ! layout_is_adjacent; then
		log "writing compacted monitor layout"
		write_compacted_monitors_conf
		reload_monitors
		host="$(pick_bar_host)"
	fi

	set_bar_host "${host}" || true

	if [[ "${already_announced}" -eq 0 ]]; then
		write_state "${host}" 1
		focus_main "${host}"
		reapply_wallpapers
		toast info "Main → ${host} (bar moved)"
		log "fallback main=${host}"
	else
		write_state "${host}" 1
	fi
}

event_stream() {
	# Hotplug only. Slow reconcile while in fallback so a drifted layout can be fixed silently.
	STATE_FILE="${STATE_FILE}" RECONCILE_SEC="${MAIN_MONITOR_RECONCILE:-6}" python3 - <<'PY'
import os, select, socket, sys, time

runtime = os.environ.get("XDG_RUNTIME_DIR", "")
sig = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "")
path = f"{runtime}/hypr/{sig}/.socket2.sock"
state_file = os.environ.get("STATE_FILE", "")
reconcile = float(os.environ.get("RECONCILE_SEC", "6"))

for _ in range(120):
    if sig and os.path.exists(path):
        break
    time.sleep(0.5)
    if not sig and os.path.isdir(f"{runtime}/hypr"):
        try:
            sig = next(d for d in os.listdir(f"{runtime}/hypr") if os.path.isdir(f"{runtime}/hypr/{d}"))
            os.environ["HYPRLAND_INSTANCE_SIGNATURE"] = sig
            path = f"{runtime}/hypr/{sig}/.socket2.sock"
        except StopIteration:
            pass
else:
    sys.stderr.write("main-monitor-hotplug: hypr socket2 not found\n")
    sys.exit(1)

sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
sock.connect(path)
sock.setblocking(False)
buf = b""
next_tick = time.monotonic() + reconcile
interesting = ("monitoradded", "monitorremoved")

while True:
    in_fallback = bool(state_file) and os.path.exists(state_file)
    timeout = max(0.2, next_tick - time.monotonic()) if in_fallback else 1.0
    readable, _, _ = select.select([sock], [], [], timeout)
    now = time.monotonic()
    if in_fallback and now >= next_tick:
        print("reconcile", flush=True)
        next_tick = now + reconcile
    elif not in_fallback:
        next_tick = now + reconcile
    if not readable:
        continue
    data = sock.recv(4096)
    if not data:
        break
    buf += data
    while b"\n" in buf:
        line, buf = buf.split(b"\n", 1)
        text = line.decode("utf-8", "replace")
        if text.startswith(interesting):
            print(text, flush=True)
PY
}

run_watch() {
	local pending=0
	apply || true

	while true; do
		pending=0
		while IFS= read -r _ev; do
			pending=1
			while IFS= read -r -t "${DEBOUNCE_SEC}" _ev2; do
				pending=1
			done || true
			if [[ "${pending}" -eq 1 ]]; then
				pending=0
				apply || true
			fi
		done < <(event_stream)
		log "event stream ended — reconnecting in 1s"
		sleep 1
		wait_for_hypr || true
	done
}

command -v hyprctl >/dev/null 2>&1 || exit 0
command -v jq >/dev/null 2>&1 || {
	log "jq not found"
	exit 1
}
command -v python3 >/dev/null 2>&1 || {
	log "python3 not found"
	exit 1
}

case "${1:-watch}" in
	apply | once)
		wait_for_hypr || exit 0
		apply
		;;
	watch)
		while ! wait_for_hypr; do
			log "waiting for Hyprland…"
			sleep 2
		done
		run_watch
		;;
	*)
		echo "usage: main-monitor-hotplug.sh [watch|apply]" >&2
		exit 2
		;;
esac
